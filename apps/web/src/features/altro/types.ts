/** Wire types of the secondary-module endpoints. Source of truth: apps/api/src/modules/{venues,trips,kits,sponsors,ledger,staff}/schema.ts. */

export interface Venue {
  id: string;
  name: string;
  address: string | null;
  city: string | null;
  capacity: number | null;
  availability: string | null;
  notes: string | null;
  createdAt: string;
  updatedAt: string;
}

export type TripStatus = "PLANNED" | "CONFIRMED" | "CANCELLED";
export type TripTransport = "CAR" | "MINIBUS" | "OTHER";

export interface Trip {
  id: string;
  eventId: string | null;
  destination: string;
  departAt: string;
  returnAt: string | null;
  transport: TripTransport;
  seats: number | null;
  costCents: number | null;
  status: TripStatus;
  notes: string | null;
  createdAt: string;
  updatedAt: string;
}

export interface Kit {
  id: string;
  item: string;
  size: string | null;
  number: number | null;
  condition: string | null;
  memberId: string | null;
  member: { id: string; firstName: string; lastName: string } | null;
  assignedAt: string | null;
  notes: string | null;
  createdAt: string;
  updatedAt: string;
}

export type SponsorStatus = "ACTIVE" | "EXPIRED" | "PROSPECT";

export interface Sponsor {
  id: string;
  name: string;
  contactName: string | null;
  email: string | null;
  phone: string | null;
  amountCents: number;
  /** Date only, "YYYY-MM-DD". */
  contractStart: string | null;
  contractEnd: string | null;
  status: SponsorStatus;
  notes: string | null;
  createdAt: string;
  updatedAt: string;
}

export type StaffRole = "COACH" | "MANAGER" | "OTHER";

export interface StaffMember {
  id: string;
  firstName: string;
  lastName: string;
  email: string | null;
  phone: string | null;
  role: StaffRole;
  qualifications: string | null;
  notes: string | null;
  userId: string | null;
  createdAt: string;
  updatedAt: string;
}

export type LedgerKind = "INCOME" | "EXPENSE";

export interface LedgerEntry {
  id: string;
  kind: LedgerKind;
  category: string;
  description: string | null;
  amountCents: number;
  /** Date only, "YYYY-MM-DD". */
  occurredOn: string;
  sponsorId: string | null;
  /** Set when the entry was generated by a payment: the Quote module owns it. */
  paymentId: string | null;
  createdAt: string;
  updatedAt: string;
}

export interface LedgerTotals {
  incomeCents: number;
  expenseCents: number;
  balanceCents: number;
}

export interface LedgerReport {
  year: number;
  totals: LedgerTotals;
  /** Always 12 items, January to December. */
  months: Array<LedgerTotals & { month: string }>;
  categories: Array<{ kind: LedgerKind; category: string; totalCents: number }>;
}
