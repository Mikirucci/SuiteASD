import { z } from 'zod';
import { patchBodySchema } from '../../lib/crud-routes.js';
import { dateOnlySchema } from '../../lib/date-only.js';
import { paginationQuerySchema } from '../../lib/pagination.js';
import { isoDateTimeSchema } from '../../lib/schemas.js';
import { ledgerKindSchema } from '../../shared/enums.js';

const idRef = z.string().min(1).max(64);
const amountCentsSchema = z.number().int().min(1).max(1_000_000_000).describe('Always positive: the kind gives the sign');
const categorySchema = z.string().trim().min(1).max(60).describe('Free label, e.g. "Quote", "Affitto palestra"');

export const createLedgerEntryBodySchema = z.object({
  kind: ledgerKindSchema,
  category: categorySchema,
  description: z.string().trim().min(1).max(500).optional(),
  amountCents: amountCentsSchema,
  occurredOn: dateOnlySchema,
  sponsorId: idRef.optional().describe('Sponsor this income comes from'),
  supplier: z.string().trim().min(1).max(120).optional().describe('Who was paid (or who paid), e.g. the shop an expense was bought from'),
  notes: z.string().trim().min(1).max(1000).optional(),
});

export const updateLedgerEntryBodySchema = patchBodySchema({
  kind: ledgerKindSchema,
  category: categorySchema,
  description: createLedgerEntryBodySchema.shape.description.nullable(),
  amountCents: amountCentsSchema,
  occurredOn: dateOnlySchema,
  sponsorId: idRef.nullable(),
  supplier: createLedgerEntryBodySchema.shape.supplier.nullable(),
  notes: createLedgerEntryBodySchema.shape.notes.nullable(),
});

export const listLedgerEntriesQuerySchema = paginationQuerySchema.extend({
  kind: ledgerKindSchema.optional(),
  category: categorySchema.optional(),
  sponsorId: idRef.optional(),
  q: z.string().trim().min(1).max(80).optional().describe('Substring of the description, the supplier or the category'),
  origin: z
    .enum(['MANUAL', 'LINKED'])
    .optional()
    .describe('MANUAL: entered by hand; LINKED: born from a payment or from the cost of a venue, kit, trip or referee'),
  from: dateOnlySchema.optional().describe('Entries on or after this day'),
  to: dateOnlySchema.optional().describe('Entries on or before this day'),
});

export const ledgerEntrySchema = z.object({
  id: z.string(),
  kind: ledgerKindSchema,
  category: z.string(),
  description: z.string().nullable(),
  amountCents: z.number().int(),
  occurredOn: dateOnlySchema,
  sponsorId: z.string().nullable(),
  supplier: z.string().nullable(),
  notes: z.string().nullable(),
  paymentId: z.string().nullable().describe('Set when the entry was generated by a payment'),
  source: z
    .enum(['PAYMENT', 'VENUE', 'KIT', 'TRIP', 'REFEREE'])
    .nullable()
    .describe('Set when another module owns the entry (a payment, or the cost of a venue, kit, trip or referee): edit it there'),
  createdAt: isoDateTimeSchema,
  updatedAt: isoDateTimeSchema,
});

export const listLedgerCategoriesQuerySchema = z.object({ kind: ledgerKindSchema });

export const ledgerCategoriesSchema = z.object({
  data: z.array(z.string()).describe('The categories already used plus the usual ones, without repeats, by name'),
});

export const ledgerReportQuerySchema = z.object({
  year: z.coerce.number().int().min(2000).max(2100).optional().describe('Defaults to the current year (UTC)'),
});

const totalsSchema = z.object({
  incomeCents: z.number().int(),
  expenseCents: z.number().int(),
  balanceCents: z.number().int().describe('incomeCents - expenseCents'),
});

export const ledgerReportSchema = z.object({
  year: z.number().int(),
  totals: totalsSchema,
  months: z
    .array(totalsSchema.extend({ month: z.string().describe('YYYY-MM') }))
    .describe('Always 12 items, January to December'),
  categories: z.array(
    z.object({ kind: ledgerKindSchema, category: z.string(), totalCents: z.number().int() }),
  ),
});

export type CreateLedgerEntryBody = z.infer<typeof createLedgerEntryBodySchema>;
export type UpdateLedgerEntryBody = z.infer<typeof updateLedgerEntryBodySchema>;
export type ListLedgerEntriesQuery = z.infer<typeof listLedgerEntriesQuerySchema>;
export type LedgerEntryDto = z.infer<typeof ledgerEntrySchema>;
export type ListLedgerCategoriesQuery = z.infer<typeof listLedgerCategoriesQuerySchema>;
export type LedgerCategoriesDto = z.infer<typeof ledgerCategoriesSchema>;
export type LedgerReportQuery = z.infer<typeof ledgerReportQuerySchema>;
export type LedgerReportDto = z.infer<typeof ledgerReportSchema>;
